// Precompiles schemas/rules.schema.json into a standalone ESM validator (no runtime code generation => no 'unsafe-eval').
// Usage: node scripts/build-validator.mjs [--check]
import Ajv from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import fs from 'node:fs'

export function generate() {
  const schema = JSON.parse(fs.readFileSync(new URL('../schemas/rules.schema.json', import.meta.url), 'utf8'))
  const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } })
  const validate = ajv.compile(schema)
  let code = standaloneCode(ajv, validate)
  // Ajv emits a CJS require() for its tiny string-length helper even in ESM mode, and CJS interop differs between
  // bundlers. Inline the helper (same algorithm as ajv/dist/runtime/ucs2length) so the validator has no runtime deps.
  const req = 'require("ajv/dist/runtime/ucs2length").default'
  if (code.includes('require(')) {
    if (!code.includes(req) || code.replaceAll(req, '').includes('require(')) throw new Error('Unexpected require() in generated validator')
    code = code.replaceAll(req, 'ucs2length')
    code = 'function ucs2length(str){const len=str.length;let length=0,pos=0,value;while(pos<len){length++;value=str.charCodeAt(pos++);if(value>=55296&&value<=56319&&pos<len){value=str.charCodeAt(pos);if((value&64512)===56320)pos++}}return length}' + code
  }
  return '// GENERATED by scripts/build-validator.mjs from schemas/rules.schema.json. Do not edit.\n// @ts-nocheck\n' + code
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const out = new URL('../src/generated/validateRules.js', import.meta.url)
  const code = generate()
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== code) { console.error('validateRules.js is stale: run npm run gen:validator'); process.exit(1) }
  } else { fs.writeFileSync(out, code); console.log('wrote', out.pathname) }
}
